"""Command-line entry point for isolated, on-demand BEMS simulations."""

import argparse
import asyncio
import logging
from datetime import datetime, UTC
from pathlib import Path

from src.bems.historical import simulate_historical
from src.config.config import config_obj
from src.databases.database_factory import create_databases
from src.logger.logging_config import setup_logging

logger = logging.getLogger(__name__)


def _parse_datetime(value: str) -> datetime:
    """Parse an ISO-8601 timestamp and reject timezone-naive values."""
    try:
        parsed = datetime.fromisoformat(value)
    except ValueError as exc:
        raise argparse.ArgumentTypeError(f"invalid ISO-8601 datetime: {value}") from exc
    if parsed.tzinfo is None or parsed.utcoffset() is None:
        raise argparse.ArgumentTypeError("datetime must include a timezone offset")
    return parsed


async def _run(args: argparse.Namespace) -> str:
    """Read history, write local reports, and close the input database."""
    bems = config_obj.bems
    if bems is None:
        raise RuntimeError("BEMS configuration was not loaded")
    databases = create_databases(config_obj)
    try:
        enabled_databases = [database for database in databases if database.enabled]
        history_database = next((database for database in enabled_databases if database.type == bems.history_database), None)
        if history_database is None:
            raise RuntimeError(f"Configured BEMS history database '{bems.history_database}' is not enabled")

        history_database.connect()

        selected_devices = set(args.devices.split(",")) if args.devices else None
        stop = args.stop or datetime.now(UTC)
        run_id = await simulate_historical(
            start=args.start,
            stop=stop,
            config=bems,
            history_database=history_database,
            output_dir=Path(args.output_dir).expanduser().resolve(),
            device_ids=selected_devices,
            run_id=args.run_id,
        )
        report_path = Path(args.output_dir).expanduser().resolve() / run_id / "index.html"
        print(f"BEMS report ready: {report_path}")
        return run_id
    finally:
        for database in databases:
            database.close()


def main() -> None:
    """Parse CLI arguments and execute one historical simulation process."""
    parser = argparse.ArgumentParser(description="Run an offline BEMS simulation against historical HEMS measurements")
    parser.add_argument("--from", dest="start", type=_parse_datetime, required=True, help="inclusive ISO-8601 start with timezone")
    parser.add_argument("--to", dest="stop", type=_parse_datetime, help="exclusive ISO-8601 end with timezone; defaults to now")
    parser.add_argument("--devices", help="comma-separated simulation device IDs; defaults to all enabled simulation devices")
    parser.add_argument("--run-id", help="optional local report folder name; an ID is generated by default")
    parser.add_argument("--output-dir", default="data/bems-reports", help="local report root directory (default: data/bems-reports)")
    args = parser.parse_args()

    setup_logging()
    asyncio.run(_run(args))


if __name__ == "__main__":  # pragma: no cover
    main()
